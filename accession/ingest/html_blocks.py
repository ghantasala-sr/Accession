"""Turn a filing's HTML into an ordered list of text and table blocks.

EDGAR filings are generated by filing agents (Workiva, Toppan Merrill, ...)
as deeply nested `<div>`s with inline styles. We walk the DOM and emit:

- a text block for each innermost block element (`div`/`p`/`li`/`h*` with
  no block-level children), and
- a table block for each top-level `<table>`, with cells cleaned up.

Inline XBRL tags (`ix:nonFraction` etc.) are transparent for text, but each
block records which XBRL facts it displays (concept + contextRef), so a chunk
can later be joined to the exact facts in the filing's instance.
"""

from __future__ import annotations

import re
import warnings
from collections import Counter
from dataclasses import dataclass, field

from bs4 import BeautifulSoup, Tag, XMLParsedAsHTMLWarning
from bs4.element import NavigableString

warnings.filterwarnings("ignore", category=XMLParsedAsHTMLWarning)

_BLOCK_TAGS = frozenset({"div", "p", "li", "h1", "h2", "h3", "h4", "h5", "h6", "table"})
_SKIP_TAGS = frozenset({"script", "style", "head", "ix:header"})
_WHITESPACE = re.compile(r"\s+")
_NUMBER = re.compile(r"\d")
_PAGE_ARTIFACT = re.compile(r"^(table of contents|page \d+|\d{1,3})$", re.IGNORECASE)
_TOC_ITEM = re.compile(r"^item\s+\d", re.IGNORECASE)
_BOLD_STYLE = re.compile(r"font-weight\s*:\s*(bold|[6-9]00)", re.IGNORECASE)
_SCALE_UNITS = {"0": "units", "3": "thousands", "6": "millions", "9": "billions"}


@dataclass(frozen=True)
class FactRef:
    concept: str
    context_id: str


@dataclass
class Block:
    kind: str  # "text" | "table"
    text: str
    is_bold: bool = False
    rows: list[list[str]] = field(default_factory=list)  # tables only
    header_row_count: int = 0  # tables only
    fact_refs: list[FactRef] = field(default_factory=list)
    scales: Counter[str] = field(default_factory=Counter)  # ix scale attrs seen

    @property
    def scale_units(self) -> str | None:
        """Display units implied by the XBRL scale of the numbers in this block."""
        if not self.scales:
            return None
        return _SCALE_UNITS.get(self.scales.most_common(1)[0][0])


@dataclass(frozen=True)
class DocumentInfo:
    """Cover-page facts tagged with `dei:` in the inline XBRL."""

    registrant: str | None
    document_type: str | None
    fiscal_year_focus: str | None
    fiscal_period_focus: str | None
    period_end: str | None


def normalize(text: str) -> str:
    return _WHITESPACE.sub(" ", text).strip()


def parse_html(html: bytes) -> tuple[DocumentInfo, list[Block]]:
    soup = BeautifulSoup(html, "lxml")
    info = _document_info(soup)
    root = soup.body or soup
    blocks = [b for b in _walk(root) if not _is_page_artifact(b)]
    return info, blocks


def _document_info(soup: BeautifulSoup) -> DocumentInfo:
    def dei(name: str) -> str | None:
        tag = soup.find("ix:nonnumeric", attrs={"name": f"dei:{name}"})
        return normalize(tag.get_text(" ")) if isinstance(tag, Tag) else None

    return DocumentInfo(
        registrant=dei("EntityRegistrantName"),
        document_type=dei("DocumentType"),
        fiscal_year_focus=dei("DocumentFiscalYearFocus"),
        fiscal_period_focus=dei("DocumentFiscalPeriodFocus"),
        period_end=dei("DocumentPeriodEndDate"),
    )


def _walk(element: Tag) -> list[Block]:
    blocks: list[Block] = []
    for child in element.children:
        if isinstance(child, NavigableString):
            # Loose text beside block siblings (e.g. directly inside ix:continuation).
            text = normalize(str(child))
            if text and type(child) is NavigableString:
                blocks.append(Block(kind="text", text=text))
            continue
        if not isinstance(child, Tag) or child.name in _SKIP_TAGS:
            continue
        if _is_hidden(child):
            continue
        if child.name == "table":
            blocks.extend(_table_blocks(child))
        elif child.name in _BLOCK_TAGS and not _has_block_descendant(child):
            text = normalize(child.get_text(" "))
            if text:
                blocks.append(
                    Block(
                        kind="text",
                        text=text,
                        is_bold=_is_bold(child),
                        fact_refs=_fact_refs(child),
                        scales=_scales(child),
                    )
                )
        else:
            blocks.extend(_walk(child))
    return blocks


def _is_hidden(tag: Tag) -> bool:
    style = str(tag.get("style", "")).replace(" ", "").lower()
    return "display:none" in style


def _has_block_descendant(tag: Tag) -> bool:
    return tag.find(_BLOCK_TAGS) is not None


def _is_bold(tag: Tag) -> bool:
    """True when every visible character in the block is bold."""
    strings = [s for s in tag.find_all(string=True) if s.strip()]
    if not strings:
        return False
    for string in strings:
        node = string.parent
        bold = False
        while isinstance(node, Tag):
            if node.name in ("b", "strong") or _BOLD_STYLE.search(str(node.get("style", ""))):
                bold = True
                break
            if node is tag:
                break
            node = node.parent
        if not bold:
            return False
    return True


def _fact_refs(tag: Tag) -> list[FactRef]:
    refs: list[FactRef] = []
    for fact in tag.find_all("ix:nonfraction"):
        concept, context = fact.get("name"), fact.get("contextref")
        if isinstance(concept, str) and isinstance(context, str):
            refs.append(FactRef(concept=concept, context_id=context))
    return refs


def _scales(tag: Tag) -> Counter[str]:
    return Counter(
        str(fact.get("scale"))
        for fact in tag.find_all("ix:nonfraction")
        if fact.get("scale") is not None and fact.get("unitref") != "usdPerShare"
    )


def _table_blocks(table: Tag) -> list[Block]:
    rows = [row for row in (_clean_row(tr) for tr in table.find_all("tr")) if any(row)]
    if not rows:
        return []
    if _is_toc(rows):
        return []

    # Layout tables (one meaningful column of prose) are really paragraphs.
    if all(sum(1 for cell in row if cell) <= 1 for row in rows) and not _looks_numeric(rows):
        return [Block(kind="text", text=" ".join(c for row in rows for c in row if c))]

    width = max(len(row) for row in rows)
    rows = [row + [""] * (width - len(row)) for row in rows]
    header_rows = _header_row_count(rows)
    return [
        Block(
            kind="table",
            text=to_markdown(rows, header_rows),
            rows=rows,
            header_row_count=header_rows,
            fact_refs=_fact_refs(table),
            scales=_scales(table),
        )
    ]


def _clean_row(tr: Tag) -> list[str]:
    """Collapse SEC layout cells: `$` | `17,853` | `` -> `$17,853`; `(` `117` `)` -> `(117)`."""
    cells = [normalize(td.get_text(" ")) for td in tr.find_all(["td", "th"])]
    starts_blank = bool(cells) and cells[0] == ""

    merged: list[str] = []
    pending_prefix = ""
    for cell in cells:
        if not cell:
            continue
        cell = re.sub(r"\(\s+", "(", re.sub(r"\s+\)", ")", cell))
        if cell in ("$", "€", "£", "("):
            pending_prefix += cell
            continue
        if merged and cell in (")", "%", ")%", "%)"):
            merged[-1] += cell
            continue
        merged.append(pending_prefix + cell)
        pending_prefix = ""

    # Header rows leave the label column blank; keep it so columns line up.
    if starts_blank and merged:
        merged.insert(0, "")
    return merged


def _is_toc(rows: list[list[str]]) -> bool:
    return sum(1 for row in rows if any(_TOC_ITEM.match(cell) for cell in row)) >= 3


def _looks_numeric(rows: list[list[str]]) -> bool:
    cells = [cell for row in rows for cell in row[1:] if cell]
    return bool(cells) and sum(1 for c in cells if _NUMBER.search(c)) / len(cells) > 0.5


def _header_row_count(rows: list[list[str]]) -> int:
    """Leading rows with a blank label column (the column headings).

    Group labels such as "Assets" or "Current assets" have a label, so they
    stay in the body even though they carry no numbers.
    """
    count = 0
    for row in rows:
        if row[0] or not any(row[1:]):
            break
        count += 1
    return count


def to_markdown(rows: list[list[str]], header_rows: int) -> str:
    def line(row: list[str]) -> str:
        return "| " + " | ".join(cell.replace("|", "/") for cell in row) + " |"

    if header_rows == 0:
        header_rows = 1
        rows = [[""] * len(rows[0]), *rows]
    out = [line(row) for row in rows[:header_rows]]
    out.append("|" + "---|" * len(rows[0]))
    out.extend(line(row) for row in rows[header_rows:])
    return "\n".join(out)


def _is_page_artifact(block: Block) -> bool:
    return block.kind == "text" and bool(_PAGE_ARTIFACT.match(block.text))
